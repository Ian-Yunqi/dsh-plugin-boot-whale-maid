import {readFileSync} from 'node:fs';
import {Script, createContext} from 'node:vm';
import assert from 'node:assert/strict';
import * as esm from '../lib/client.js';
const pkg = JSON.parse(readFileSync(new URL('../package.json', import.meta.url), 'utf8'));
const entry = typeof pkg.exports['./client'] === 'string' ? pkg.exports['./client'] : pkg.exports['./client'].default;
const registrations = [];
const context = createContext({window: {__ModuleLoader__: {load(row) {registrations.push(row);}}}});
new Script(readFileSync(new URL('../' + entry, import.meta.url), 'utf8')).runInContext(context);
assert.equal(registrations.length, 1);
assert.equal(registrations[0].id, pkg.name);
const api = registrations[0].factory(() => {throw Error('Unexpected dependency');});
assert.deepEqual(Object.keys(api).sort(), Object.keys(esm).sort());
assert.equal(typeof api.apply, 'function');
assert.equal(typeof api.createBootShow, 'function');
assert.equal(JSON.stringify(api.inject), JSON.stringify(pkg.dsh.client.inject));
assert.equal(JSON.stringify(api.BOOT_SEGMENTS), JSON.stringify(esm.BOOT_SEGMENTS));
assert.equal(JSON.stringify(api.BOOT_ASSETS), JSON.stringify(esm.BOOT_ASSETS));
api.apply(null).dispose();
console.log('PASS: package client entry parses as a classic script, registers the correct factory, and exports the expected API.');
